import {createHash} from 'node:crypto';

const GIT_SHA=/^[0-9a-f]{40}$/;
const DEPLOYMENT_ID=/^[0-9a-f]{8}-(?:[0-9a-f]{4}-){3}[0-9a-f]{12}$/;

/**
 * Source-artifact attestation for an operator-controlled Worker release.
 * The digest describes committed src/worker.mjs, not Cloudflare's final
 * internally compiled/uploaded representation.
 */
export function makeReleaseProvenance(commit,source){
 if(!GIT_SHA.test(commit))throw Error('RELEASE_COMMIT_INVALID');
 if(typeof source!=='string'||!source.startsWith('// Generated by scripts/build-worker.mjs.')||source.length<1000)
  throw Error('RELEASE_SOURCE_ARTIFACT_INVALID');
 const artifact_sha256=createHash('sha256').update(source,'utf8').digest('hex');
 return {artifact_sha256,message:'Verified main '+commit+'; artifact '+artifact_sha256,tag:'main-'+commit.slice(0,7)};
}

/** Full releases require a reviewed exact live deployment ID to prevent stale rollouts. */
export function requireExpectedLiveDeployment(manifest,live){
 const expected=manifest?.production_deployment_id;
 if(typeof expected!=='string'||!DEPLOYMENT_ID.test(expected))throw Error('RELEASE_BASELINE_EVIDENCE_REQUIRED');
 if(!live?.deployment_id||live.deployment_id!==expected)throw Error('PRODUCTION_BASELINE_CHANGED');
 return live;
}

/** Verified post-upload lineage must match exact source commit and artifact. */
export function assertNewReleaseProvenance(previous,actual,commit,artifact_sha256){
 if(!DEPLOYMENT_ID.test(previous?.deployment_id||'')||!DEPLOYMENT_ID.test(actual?.deployment_id||'')||
    actual.deployment_id===previous.deployment_id||actual.commit!==commit||
    actual.artifact_sha256!==artifact_sha256)
  throw Error('PRODUCTION_RELEASE_PROVENANCE_MISMATCH');
 return true;
}
