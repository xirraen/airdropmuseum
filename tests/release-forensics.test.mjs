import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,readFileSync,rmSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {execFileSync} from 'node:child_process';
import {gzipSync} from 'node:zlib';
import {
 gitBlobSha,parseWorkerSourceMap,sourceAssets,compareSourceMap,runForensics
} from '../scripts/release-forensics.mjs';

const run=(cwd,args)=>execFileSync('git',args,{cwd,encoding:'utf8'}).trim();
const encoded=(text)=>({body:gzipSync(Buffer.from(text)).toString('base64'),encoding:'gzip',type:'text/javascript'});
const makeWorker=(assets)=>'// Generated by scripts/build-worker.mjs. Do not edit directly.\nexport const assets='+JSON.stringify(assets)+';\nexport default {};';
const mkMap=(worker)=>({version:3,sources:['src/api.mjs','src/worker.mjs'],sourcesContent:['export const api = 1;',worker]});
const multipart=(map)=>'--test-boundary\r\nContent-Disposition: form-data; name="worker.js.map"; filename="worker.js.map"\r\nContent-Type: application/json\r\n\r\n'+JSON.stringify(map)+'\r\n--test-boundary\r\nContent-Disposition: form-data; name="worker.js"; filename="worker.js"\r\n\r\nexport default {};\r\n--test-boundary--\r\n';
const deployment='0fd82ac4-7201-4eb7-a3c9-4fa26d66076f',version='4765aba5-550e-40de-a945-2c287d4ec328';

test('Git blob hashes use exact UTF-8 length and content',()=>{
 assert.equal(gitBlobSha('hello'),'b6fc4c620b67d95f953a5c1c1230aaab5db5a1b0');
 assert.equal(gitBlobSha(Buffer.from('hello')),gitBlobSha('hello'));
 assert.notEqual(gitBlobSha('é'),gitBlobSha('e'));
});

test('source map parser accepts multipart content without accepting malformed or oversized payload',()=>{
 const map=mkMap(makeWorker({'/app.js':encoded('console.log(1)')}));
 assert.deepEqual(parseWorkerSourceMap(multipart(map)),map);
 assert.throws(()=>parseWorkerSourceMap('bad'),/WORKER_CONTENT_INVALID/);
 assert.throws(()=>parseWorkerSourceMap('--test-boundary\r\n--test-boundary--\r\n'),/WORKER_SOURCE_MAP_MISSING/);
 assert.throws(()=>parseWorkerSourceMap(multipart({version:2,sources:[],sourcesContent:[]})),/WORKER_SOURCE_MAP_INVALID/);
 assert.throws(()=>sourceAssets('not a generated Worker'),/GENERATED_ASSETS_UNAVAILABLE/);
});

test('binary static assets with null compression are compared byte-for-byte',()=>{
 const binary=Buffer.from([0,1,2,127,128,255]);
 const worker=makeWorker({'/brand.jpg':{body:binary.toString('base64'),encoding:null,type:'image/jpeg'}});
 const map=mkMap(worker);
 const tracked={'src/api.mjs':gitBlobSha('export const api = 1;'),
  'src/worker.mjs':gitBlobSha(worker),'dist/brand.jpg':gitBlobSha(binary)};
 const result=compareSourceMap(map,tracked);
 assert.equal(result.embedded_assets_matched,1);
 assert.equal(result.tracked_sources_matched,2);
 assert.deepEqual(result.embedded_asset_mismatches,[]);
});

test('read-only comparator reports stale generated files and never infers an attested Git source',()=>{
 const worker=makeWorker({'/app.js':encoded('console.log(1)'),' /bad':encoded('bad')});
 const map=mkMap(worker);
 const tracked={'src/api.mjs':gitBlobSha('export const api = 1;'),'src/worker.mjs':gitBlobSha('old worker'), 'dist/app.js':gitBlobSha('console.log(1)')};
 assert.throws(()=>compareSourceMap(map,tracked),/EMBEDDED_ASSET_PATH_INVALID/);
 const valid=mkMap(makeWorker({'/app.js':encoded('console.log(1)')}));
 const found=compareSourceMap(valid,tracked);
 assert.deepEqual(found.tracked_source_mismatches,['src/worker.mjs']);
 assert.equal(found.embedded_assets_matched,1);
 assert.equal(found.external_or_virtual_inputs,0);
});

test('optional built-root verification requires an exact candidate checkout; it does not bypass release gates',async()=>{
 const dir=mkdtempSync(join(tmpdir(),'am-read-only-forensic-'));
 try{
  mkdirSync(join(dir,'src'),{recursive:true});
  mkdirSync(join(dir,'dist'),{recursive:true});
  writeFileSync(join(dir,'src/api.mjs'),'export const api = 1;');
  writeFileSync(join(dir,'dist/app.js'),'console.log(1)');
  writeFileSync(join(dir,'dist/aggregator-ui-bundle.js'),'old generated asset');
  writeFileSync(join(dir,'src/worker.mjs'),'old generated Worker');
  run(dir,['init','-q']);run(dir,['config','user.email','unit-test@example.invalid']);run(dir,['config','user.name','Test']);
  run(dir,['add','.']);run(dir,['commit','-qm','fixture']);
  const commit=run(dir,['rev-parse','HEAD']);
  const builtAssets={'/app.js':encoded('console.log(1)'),
   '/aggregator-ui-bundle.js':encoded('new built bundle')};
  const generated=makeWorker(builtAssets);
  writeFileSync(join(dir,'dist/aggregator-ui-bundle.js'),'new built bundle');
  writeFileSync(join(dir,'src/worker.mjs'),generated);
  const body=multipart(mkMap(generated));
  const calls=[];
  const fetcher=async url=>{
   calls.push(url);
   if(url.endsWith('/deployments'))return {ok:true,json:async()=>({success:true,result:{deployments:[{id:deployment,versions:[{version_id:version,percentage:100}]}]}})};
   if(url.includes('/versions/'))return {ok:true,json:async()=>({success:true,result:{annotations:{'workers/triggered_by':'version_upload'}}})};
   if(url.endsWith('/content/v2'))return {ok:true,headers:{get:()=>String(body.length)},text:async()=>body};
   throw Error('UNEXPECTED_URL');
  };
  const partial=await runForensics({commit,token:'LOCAL_MOCK_TOKEN',root:dir,fetcher});
  assert.equal(partial.status,'PARTIAL_OR_MISMATCHED');
  assert.deepEqual(partial.tracked_source_mismatches,['src/worker.mjs']);
  assert.deepEqual(partial.embedded_asset_mismatches,['dist/aggregator-ui-bundle.js']);
  const complete=await runForensics({commit,token:'LOCAL_MOCK_TOKEN',root:dir,builtRoot:dir,fetcher});
  assert.equal(complete.status,'CONTENT_MATCH_ONLY_NOT_ATTESTED');
  assert.equal(complete.tracked_sources_matched,2);
  assert.equal(complete.embedded_assets_matched,2);
  assert.equal(complete.release_authorized,false);
  assert.equal(complete.production.version_annotation_present,false);
  assert.equal(calls.length,8);
  assert.equal(readFileSync(join(dir,'src/api.mjs'),'utf8'),'export const api = 1;');
  await assert.rejects(runForensics({commit:'a'.repeat(40),token:'LOCAL_MOCK_TOKEN',root:dir,builtRoot:dir,fetcher}),/FORENSIC_BUILD_COMMIT_MISMATCH|fatal|not a valid object name/);
 }finally{rmSync(dir,{recursive:true,force:true});}
});

test('forensic API rejects missing token before any network call',async()=>{
 let calls=0;
 await assert.rejects(runForensics({token:'',commit:'a'.repeat(40),fetcher:async()=>{calls++;throw Error('UNEXPECTED_FETCH');}}),/CLOUDFLARE_TOKEN_REQUIRED/);
 await assert.rejects(runForensics({token:'MOCK',commit:'invalid',fetcher:async()=>{calls++;throw Error('UNEXPECTED_FETCH');}}),/FORENSIC_COMMIT_INVALID/);
 assert.equal(calls,0);
});

