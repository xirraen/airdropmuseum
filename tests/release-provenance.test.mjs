import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {getLiveDeploymentIdentity,getLiveReleaseBaseline} from '../scripts/release-policy.mjs';
import {makeReleaseProvenance,requireExpectedLiveDeployment,assertNewReleaseProvenance} from '../scripts/release-provenance.mjs';

const commit='a'.repeat(40);
const baseline='ab00cdef-1234-5678-9abc-0123456789ab';
const next='cd00cdef-1234-5678-9abc-0123456789ab';
const source='// Generated by scripts/build-worker.mjs. Do not edit directly.\n'+'// code\n'.repeat(200);

test('operator provenance includes SHA-256 of generated Worker source and exact git SHA',()=>{
 const result=makeReleaseProvenance(commit,source);
 const expected=createHash('sha256').update(source,'utf8').digest('hex');
 assert.equal(result.artifact_sha256,expected);
 assert.equal(result.message,'Verified main '+commit+'; artifact '+expected);
 assert.equal(result.tag,'main-aaaaaaa');
 for(const bad of ['',commit.slice(1),'x'.repeat(40)])assert.throws(()=>makeReleaseProvenance(bad,source),/RELEASE_COMMIT_INVALID/);
 for(const bad of ['', 'not a generated Worker', '// Generated by scripts/build-worker.mjs.'])assert.throws(()=>makeReleaseProvenance(commit,bad),/RELEASE_SOURCE_ARTIFACT_INVALID/);
});

test('full release requires a reviewed, immutable current live deployment ID',()=>{
 const manifest={production_deployment_id:baseline},live={deployment_id:baseline};
 assert.equal(requireExpectedLiveDeployment(manifest,live),live);
 assert.throws(()=>requireExpectedLiveDeployment({},live),/RELEASE_BASELINE_EVIDENCE_REQUIRED/);
 assert.throws(()=>requireExpectedLiveDeployment({production_deployment_id:'unknown'},live),/RELEASE_BASELINE_EVIDENCE_REQUIRED/);
 assert.throws(()=>requireExpectedLiveDeployment(manifest,{deployment_id:next}),/PRODUCTION_BASELINE_CHANGED/);
 assert.throws(()=>requireExpectedLiveDeployment(manifest,{}),/PRODUCTION_BASELINE_CHANGED/);
});

test('a deployed Worker is not accepted without matching source provenance and a new deployment ID',()=>{
 const provenance=makeReleaseProvenance(commit,source);
 const old={deployment_id:baseline};
 const deployed={deployment_id:next,commit,artifact_sha256:provenance.artifact_sha256};
 assert.equal(assertNewReleaseProvenance(old,deployed,commit,provenance.artifact_sha256),true);
 for(const bad of [
  {...deployed,deployment_id:baseline},
  {...deployed,commit:'b'.repeat(40)},
  {...deployed,artifact_sha256:'f'.repeat(64)},
  {...deployed,deployment_id:'bad'}
 ])assert.throws(()=>assertNewReleaseProvenance(old,bad,commit,provenance.artifact_sha256),/PRODUCTION_RELEASE_PROVENANCE_MISMATCH/);
});

test('live deployment identity is readable without trusting a missing version annotation',async()=>{
 const fetcher=async (url,options)=>{
  assert.equal(options.headers.Authorization,'Bearer MOCK_TOKEN');
  if(url.endsWith('/deployments'))return {ok:true,json:async()=>({success:true,result:{
   deployments:[{id:baseline,versions:[{version_id:'c0ffee00-1234-4567-9876-123456789012',percentage:100}]}]}})};
  return {ok:true,json:async()=>({success:true,result:{annotations:{'workers/triggered_by':'version_upload'}}})};
 };
 const identity=await getLiveDeploymentIdentity('MOCK_TOKEN',{fetcher});
 assert.equal(identity.deployment_id,baseline);
 await assert.rejects(getLiveReleaseBaseline('MOCK_TOKEN',{fetcher}),/PRODUCTION_BASELINE_UNATTESTED/);
});

test('operator full release is fail closed and attaches provenance without changing gate counts',()=>{
 const source=readFileSync('scripts/release-production.mjs','utf8');
 assert.match(source,/requireExpectedLiveDeployment/);
 assert.match(source,/getLiveDeploymentIdentity/);
 assert.match(source,/getLiveReleaseBaseline/);
 assert.match(source,/assertNewReleaseProvenance/);
 assert.match(source,/--strict/);
 assert.match(source,/--message/);
 assert.match(source,/--tag/);
 assert.match(source,/verifyReleaseEvidence/);
 const p=spawnSync(process.execPath,['scripts/release-production.mjs'],{encoding:'utf8',
  env:{PATH:process.env.PATH,HOME:process.env.HOME}});
 assert.notEqual(p.status,0);
 assert.match(p.stderr,/PRODUCTION_RELEASE_BLOCKED/);
});
